class _Colormap:
    """Callable colormap — maps float [0,1] to (R, G, B) int tuple."""

    def __init__(self, data):
        # Ensure exactly 256 entries via interpolation if needed
        if len(data) != 256:
            indices = np.linspace(0, len(data) - 1, 256)
            self._lut = np.stack([
                np.interp(indices, np.arange(len(data)), data[:, c]).astype(np.uint8)
                for c in range(3)
            ], axis=1)
        else:
            self._lut = data

    def __call__(self, value):
        """Map float value in [0, 1] to (R, G, B) int tuple."""
        idx = int(max(0.0, min(1.0, float(value))) * 255)
        r, g, b = self._lut[idx]
        return (int(r), int(g), int(b))


